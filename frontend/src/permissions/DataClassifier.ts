// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Classify a known MM data field.
 * Returns null if the field is not registered in the classification map.
 *
 * Spec §14: "Do not classify data merely by its name."
 * If a field is not in this map, it needs a classification review before use.
 */
export function classifyField(fieldKey: string): DataClass | null {
  return MM_DATA_CLASSIFICATIONS[fieldKey] ?? null;
}

/**
 * Get the retention policy for a data class.
 */
export function getRetentionPolicy(dataClass: DataClass): RetentionPolicy {
  return RETENTION_POLICIES[dataClass];
}

/**
 * Returns true if a data class must NOT be stored to persistent storage.
 */
export function mustNotPersist(dataClass: DataClass): boolean {
  return dataClass === DataClass.SENSITIVE_CONTEXT || dataClass === DataClass.TEMPORARY_DATA;
}

/**
 * Returns true if a data class requires explicit user consent before transmission.
 */
export function requiresConsentForTransmission(dataClass: DataClass): boolean {
  return (
    dataClass === DataClass.SENSITIVE_CONTEXT ||
    dataClass === DataClass.PERSONAL_DATA ||
    dataClass === DataClass.USER_DATA
  );
}

/**
 * Returns all fields classified at a given level.
 * Useful for privacy audits (spec §34).
 */
export function getFieldsByClass(dataClass: DataClass): string[] {
  return Object.entries(MM_DATA_CLASSIFICATIONS)
    .filter(([, cls]) => cls === dataClass)
    .map(([key]) => key);
}
