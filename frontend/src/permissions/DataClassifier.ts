export interface RetentionPolicy {
  /** Human-readable description of when this data is discarded */
  policy: string;
  /** Storage mechanism (or 'none' if not persisted) */
  storage: 'none' | 'memory' | 'sessionStorage' | 'localStorage' | 'indexedDB' | 'server';
  /** Maximum age in seconds before data must be discarded. -1 means user-controlled. */
  maxAgeSeconds: number;
}

