/**
 * Music Mirror — Data Classification System (Spec §14)
 *
 * Classify data before implementing storage or transmission.
 * Do not classify data merely by its name — classify according to actual usage.
 *
 * Rule: Apply minimum necessary protection and retention to each category.
 *
 * Classification hierarchy (most → least sensitive):
 *   SENSITIVE_CONTEXT > PERSONAL_DATA > USER_DATA > DEVICE_DATA >
 *   DERIVED_DATA > PROVIDER_DATA > TEMPORARY_DATA > INTERNAL > PUBLIC
 */

// ---------------------------------------------------------------------------
// Classification Enum
// ---------------------------------------------------------------------------

export const DataClass = {
  /**
   * Raw biometric or sensor data.
   * Examples: raw camera frames, raw audio input, precise geolocation.
   * Handling: Do not store. Process transiently. Do not transmit without explicit consent.
   */
  SENSITIVE_CONTEXT: 'SENSITIVE_CONTEXT',

  /**
   * Data that can directly identify or profile a specific person.
   * Examples: user ID, email, name, IP address.
   * Handling: Store only when necessary. Encrypt at rest. Minimize retention.
   */
  PERSONAL_DATA: 'PERSONAL_DATA',

  /**
   * Data generated by user activity that is not directly identifying on its own,
   * but could become identifying in combination.
   * Examples: listening history, search history, playlists, feedback, favorites.
   * Handling: Retain only for functional purpose. User must be able to delete it.
   */
  USER_DATA: 'USER_DATA',

  /**
   * Data about the user's device or browser environment.
   * Examples: user agent, screen resolution, hardware capabilities.
   * Handling: Do not retain unnecessarily. Do not transmit to third parties.
   */
  DEVICE_DATA: 'DEVICE_DATA',

  /**
   * Data derived by inference from other data.
   * Examples: inferred emotion from camera, recommended tracks, mood classification.
   * Handling: Treat derived personal inference with same care as its source data.
   * If source was SENSITIVE_CONTEXT, derived inference may be PERSONAL_DATA.
   */
  DERIVED_DATA: 'DERIVED_DATA',

  /**
   * Data received from external providers that MM stores or processes.
   * Examples: YouTube video metadata, backend catalog data.
   * Handling: Do not trust blindly. Validate before use. Retain bounded by TTL.
   */
  PROVIDER_DATA: 'PROVIDER_DATA',

  /**
   * Data that exists only for the duration of an operation or session.
   * Examples: camera frames during inference, search query in flight, audio chunks.
   * Handling: Discard when operation completes. Must not persist to storage.
   */
  TEMPORARY_DATA: 'TEMPORARY_DATA',

  /**
   * Internal system data not tied to user identity.
   * Examples: cache metadata, performance metrics, error codes, server version.
   * Handling: May be stored for operational purposes. Do not include user identity.
   */
  INTERNAL: 'INTERNAL',

  /**
   * Publicly available data with no sensitivity.
   * Examples: track title, artist name, YouTube video ID.
   * Handling: No special restrictions. May be cached and transmitted freely.
   */
  PUBLIC: 'PUBLIC',
} as const;

export type DataClass = typeof DataClass[keyof typeof DataClass];

